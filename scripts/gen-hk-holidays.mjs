// Regenerates src/lib/dates/hkHolidays.ts from the 1823 government feed.
// Run: node scripts/gen-hk-holidays.mjs
//
// Bundled at build time rather than fetched at runtime for three reasons: the
// feed serves no CORS headers so the browser cannot read it at all, the
// calendar has to work offline, and a static table keeps the tests
// deterministic. The feed covers a rolling three years; next year's holidays
// are gazetted each May, so re-run this annually.
import { writeFileSync } from 'node:fs'

const FEED = 'https://www.1823.gov.hk/common/ical/en.json'
const OUT = 'src/lib/dates/hkHolidays.ts'

const res = await fetch(FEED)
if (!res.ok) throw new Error(`${FEED} -> HTTP ${res.status}`)
// The feed is served with a UTF-8 BOM, which JSON.parse rejects.
const feed = JSON.parse((await res.text()).replace(/^﻿/, ''))

const events = feed?.vcalendar?.[0]?.vevent
if (!Array.isArray(events) || events.length === 0) throw new Error('No vevent array in the feed.')

const dayMs = 86_400_000
const toDate = (compact) =>
  new Date(+compact.slice(0, 4), +compact.slice(4, 6) - 1, +compact.slice(6, 8))

const holidays = {}
for (const ev of events) {
  const start = ev?.dtstart?.[0]
  const summary = ev?.summary
  if (typeof start !== 'string' || !/^\d{8}$/.test(start) || typeof summary !== 'string') {
    throw new Error(`Malformed vevent: ${JSON.stringify(ev)}`)
  }
  // DTEND is exclusive. Every entry is single-day today, but expand the range
  // anyway so a future multi-day entry does not silently lose its tail.
  const end = /^\d{8}$/.test(ev?.dtend?.[0] ?? '') ? ev.dtend[0] : null
  const days = end ? Math.max(1, Math.round((toDate(end) - toDate(start)) / dayMs)) : 1
  for (let i = 0; i < days; i++) {
    const d = new Date(toDate(start).getTime() + i * dayMs)
    const key = `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(
      d.getDate(),
    ).padStart(2, '0')}`
    holidays[key] = summary
  }
}

const dates = Object.keys(holidays).sort()
const years = [...new Set(dates.map((d) => d.slice(0, 4)))].sort()
const body = dates.map((d) => `  '${d}': ${JSON.stringify(holidays[d])},`).join('\n')

writeFileSync(
  OUT,
  `// GENERATED by scripts/gen-hk-holidays.mjs — do not edit by hand.
// Source: ${FEED}
// Generated: ${new Date().toISOString().slice(0, 10)} · ${dates.length} holidays, ${years[0]}–${years[years.length - 1]}
// Re-run annually: next year's holidays are gazetted each May.

/** Local 'yyyy-MM-dd' -> official English holiday name. */
export const HK_HOLIDAYS: Readonly<Record<string, string>> = Object.freeze({
${body}
})

/** Years the bundled table actually covers. Outside this range the calendar
 *  shows no holidays, which means "unknown", not "none". */
export const HK_HOLIDAY_YEARS = Object.freeze({
  first: ${years[0]},
  last: ${years[years.length - 1]},
})
`,
  'utf8',
)

console.log(`${OUT}: ${dates.length} holidays, ${years.join(', ')}`)

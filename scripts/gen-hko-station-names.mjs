// Regenerates src/lib/weather/stationNames.ts from the HKO rhrread feed.
// Run: node scripts/gen-hko-station-names.mjs
//
// The feed carries no station ids — the English place name IS the key, here
// and in stationCodes.ts — so the Chinese names are paired to it BY POSITION
// from the same endpoint fetched twice, once per language. That pairing is
// the fragile part, which is why the table is generated and checked in rather
// than built in the browser: a shift in the feed must break this script,
// visibly, and never the running app. Re-run when HKO adds a station.
import { writeFileSync } from 'node:fs'

const FEED = 'https://data.weather.gov.hk/weatherAPI/opendata/weather.php?dataType=rhrread&lang='
const OUT = 'src/lib/weather/stationNames.ts'

const places = async (lang) => {
  const res = await fetch(`${FEED}${lang}`)
  if (!res.ok) throw new Error(`${FEED}${lang} -> HTTP ${res.status}`)
  const j = await res.json()
  const data = j?.temperature?.data
  if (!Array.isArray(data) || data.length === 0) throw new Error(`No temperature data for ${lang}`)
  return data.map((d) => d.place)
}

const [en, tc] = await Promise.all([places('en'), places('tc')])
if (en.length !== tc.length) {
  throw new Error(`Station counts differ: ${en.length} English, ${tc.length} Chinese.`)
}

const names = {}
for (let i = 0; i < en.length; i++) {
  const [e, c] = [en[i], tc[i]]
  if (typeof e !== 'string' || typeof c !== 'string' || e === '' || c === '') {
    throw new Error(`Malformed pair at ${i}: ${JSON.stringify([e, c])}`)
  }
  // An English name that came back with Chinese characters, or the reverse,
  // means the two lists are no longer in the same order.
  if (/[一-鿿]/.test(e) || !/[一-鿿]/.test(c)) {
    throw new Error(`Feeds look misaligned at ${i}: ${e} / ${c}`)
  }
  names[e] = c
}

const keys = Object.keys(names).sort()
// Single quotes to match the rest of the source; "King's Park" is the one
// name that cannot have them.
const q = (v) => (v.includes("'") ? JSON.stringify(v) : `'${v}'`)
const body = keys.map((k) => `  ${q(k)}: ${q(names[k])},`).join('\n')

writeFileSync(
  OUT,
  `// GENERATED by scripts/gen-hko-station-names.mjs — do not edit by hand.
// Source: ${FEED}{en,tc}
// Generated: ${new Date().toISOString().slice(0, 10)} · ${keys.length} stations

/** HKO's English station name -> its Chinese name. The English name is the
 *  identity key everywhere (see stationCodes.ts); this is display only. */
export const HKO_STATION_NAMES_TC: Readonly<Record<string, string>> = Object.freeze({
${body}
})
`,
  'utf8',
)

console.log(`${OUT}: ${keys.length} stations`)
